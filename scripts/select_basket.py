"""
Builds public/assets/js/lib/basket.js from trade-volume data.

Usage: python3 scripts/select_basket.py CANDIDATES.json
CANDIDATES.json is a list of {id, name, avgprice, avgvol, avgval} where avgvol is the
30-day average official GE daily volume (from the Weird Gloop history API) and
avgval = avgprice * avgvol (average gp traded per day).

Selection rules
- Not excluded by categories.EXCLUDE (cosmetics, duplicates, notes, lottery items, teleports, keys...)
- Trades at least MIN_VOLUME units a day on average
- Averages at least MIN_VALUE_SKILLING gp/day traded (consumables & skilling supplies)
  or MIN_VALUE_GEAR gp/day (equipment), so junk and dead items are left out

Weighting
- Each category gets a fixed share of the index (categories.CATEGORY_SHARES)
- Within a category, items are weighted by the square root of their daily gp traded,
  so popular items count for more without a few huge items drowning out the rest
"""
import json, math, sys, datetime, os
sys.path.insert(0, os.path.dirname(__file__))
from categories import categorise, CATEGORY_SHARES

MIN_VOLUME = 10
MIN_VALUE_SKILLING = 25_000_000
MIN_VALUE_GEAR = 75_000_000
GEAR = {"Mega rares", "High-end PvM gear", "Mid-tier gear & PvM supplies"}
ORDER = list(CATEGORY_SHARES)

cands = json.load(open(sys.argv[1]))
chosen = {c: [] for c in ORDER}
for r in cands:
    cat = categorise(r["name"], r["avgprice"])
    if not cat or r["avgvol"] < MIN_VOLUME:
        continue
    if r["avgval"] < (MIN_VALUE_GEAR if cat in GEAR else MIN_VALUE_SKILLING):
        continue
    chosen[cat].append(r)

lines = [
    "// Default OSRS \"RPI\" basket. GENERATED by scripts/select_basket.py; edit that, not this file.",
    f"// Built {datetime.date.today().isoformat()} from 30-day average Grand Exchange volumes.",
    "// weight = % of the index. Within a category, weight is proportional to sqrt(avg daily gp traded).",
    "// If an item has no data for a period it is left out and the remaining weights are rescaled.",
    "",
    "export const BASKET_CATEGORIES = [",
]
total_items = 0
for cat in ORDER:
    items = sorted(chosen[cat], key=lambda r: -r["avgval"])
    roots = [math.sqrt(r["avgval"]) for r in items]
    s = sum(roots)
    lines.append(f"  {{\n    name: {json.dumps(cat)},\n    share: {CATEGORY_SHARES[cat]},\n    items: [")
    for r, rt in zip(items, roots):
        w = CATEGORY_SHARES[cat] * rt / s
        lines.append(f"      [{int(r['id'])}, {json.dumps(r['name'])}, {w:.5f}],")
    lines.append("    ],\n  },")
    total_items += len(items)
lines += [
    "];",
    "",
    "/** Flat { itemName: weight } map of the default basket. */",
    "export const DEFAULT_BASKET = Object.fromEntries(BASKET_CATEGORIES.flatMap((c) => c.items.map(([, n, w]) => [n, w])));",
    "",
    "/** itemName -> item id */",
    "export const ITEM_ID = Object.fromEntries(BASKET_CATEGORIES.flatMap((c) => c.items.map(([id, n]) => [n, id])));",
    "",
    "/** itemName -> category name */",
    "export const ITEM_CATEGORY = Object.fromEntries(BASKET_CATEGORIES.flatMap((c) => c.items.map(([, n]) => [n, c.name])));",
    "",
]
out = os.path.join(os.path.dirname(__file__), "..", "public", "assets", "js", "lib", "basket.js")
open(out, "w").write("\n".join(lines))
print(total_items, "items", {c: len(chosen[c]) for c in ORDER})
